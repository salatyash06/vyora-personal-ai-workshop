import { useState } from "react";
import { ShieldCheck } from "lucide-react";

import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { useVyora } from "@/lib/vyora/store";
import { Orb } from "./Orb";
import { DemoBadge } from "./StatusPill";

export function ConnectScreen() {
  const { connect, connecting, errorMessage, isDemo } = useVyora();
  const [token, setToken] = useState("");

  return (
    <main className="flex min-h-screen items-center justify-center px-4 py-10">
      <div className="panel w-full max-w-md p-8">
        <div className="flex flex-col items-center gap-4 text-center">
          <Orb state="disconnected" size={88} />
          <div>
            <h1 className="text-2xl font-semibold tracking-[0.18em] text-glow">VYORA</h1>
            <p className="mt-1 text-sm text-muted-foreground">
              Your voice. Your workspace. Your assistant.
            </p>
          </div>
          {isDemo && <DemoBadge />}
        </div>

        <form
          className="mt-8 flex flex-col gap-4"
          onSubmit={(event) => {
            event.preventDefault();
            void connect(token).catch(() => {});
          }}
        >
          <div className="flex flex-col gap-2">
            <Label htmlFor="connection-token">Connection token</Label>
            <Input
              id="connection-token"
              type="password"
              autoComplete="off"
              value={token}
              onChange={(event) => setToken(event.target.value)}
              placeholder="Paste the token printed by the local assistant"
              aria-describedby="token-help connection-error"
              className="bg-input"
            />
            <p id="token-help" className="text-xs text-muted-foreground">
              The token is generated by the Python assistant on your machine. It is kept in this
              browser session only and cleared when the window closes.
            </p>
          </div>

          {errorMessage && (
            <p id="connection-error" role="alert" className="text-sm text-destructive">
              {errorMessage}
            </p>
          )}

          <Button type="submit" disabled={connecting || token.trim().length === 0}>
            <ShieldCheck className="size-4" aria-hidden="true" />
            {connecting ? "Validating…" : "Connect"}
          </Button>

          {isDemo && (
            <p className="text-xs text-muted-foreground">
              Demo mode accepts any token of six characters or more so you can explore the
              interface. Nothing on your computer is accessed.
            </p>
          )}
        </form>
      </div>
    </main>
  );
}
